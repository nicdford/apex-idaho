#!/usr/bin/env node
/**
 * Keeps this app's design in lockstep with the WordPress block theme, which
 * stays the single source of the design:
 *
 * - src/styles/tokens.css: the custom properties WordPress generates from
 *   theme.json (--wp--preset--color--red, --wp--preset--font-size--huge, …),
 *   the has-*-color / has-*-font-size classes, the element styles (headings,
 *   links, buttons) and the section styles (styles/sections/*.json), with the
 *   same low specificity WordPress uses. HTML rendered by WordPress (page
 *   content from the REST API) therefore styles exactly as on WordPress.
 * - src/styles/theme/*.css: copies of the theme's assets/css/theme.css and
 *   blocks/blocks.css.
 *
 *   npm run sync:tokens
 *
 * The output is committed, so builds don't need the theme folder.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const themeDir = resolve(here, '../../wordpress/wp-content/themes/apex-idaho');
const themeJsonPath = resolve(themeDir, 'theme.json');
const outPath = resolve(here, '../src/styles/tokens.css');

const theme = JSON.parse(readFileSync(themeJsonPath, 'utf8'));
const { settings, styles } = theme;

/** "var:preset|spacing|40" -> "var(--wp--preset--spacing--40)" */
const ref = (value) =>
  typeof value === 'string' && value.startsWith('var:')
    ? `var(--wp--${value.slice(4).split('|').join('--')})`
    : value;

const toPx = (value) => {
  const n = parseFloat(value);
  return value.endsWith('rem') || value.endsWith('em') ? n * 16 : n;
};
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;

/** Linear clamp between the theme's fluid viewport bounds, as WordPress does. */
const fluid = settings.typography.fluid ?? {};
const minVw = toPx(fluid.minViewportWidth ?? '320px');
const maxVw = toPx(fluid.maxViewportWidth ?? '1600px');
const fontSize = ({ size, fluid: f }) => {
  if (!f || f === false || !f.min || !f.max) return size;
  const min = toPx(f.min);
  const max = toPx(f.max);
  const factor = +((max - min) / (maxVw - minVw)).toFixed(4);
  return `clamp(${rem(min)}, calc(${rem(min)} + (100vw - ${rem(minVw)}) * ${factor}), ${rem(max)})`;
};

const lines = [];
const out = (s = '') => lines.push(s);

out('/* Generated by scripts/sync-tokens.mjs from the block theme\'s theme.json. Do not edit by hand. */');
out();
out(':root {');
for (const c of settings.color.palette) out(`\t--wp--preset--color--${c.slug}: ${c.color};`);
for (const g of settings.color.gradients ?? []) out(`\t--wp--preset--gradient--${g.slug}: ${g.gradient};`);
for (const f of settings.typography.fontSizes) out(`\t--wp--preset--font-size--${f.slug}: ${fontSize(f)};`);
for (const f of settings.typography.fontFamilies) {
  // The first family comes from next/font (src/app/fonts.ts); keep the fallbacks.
  const fallbacks = f.fontFamily.split(',').slice(1).join(',').trim();
  out(`\t--wp--preset--font-family--${f.slug}: var(--font-${f.slug}), ${fallbacks};`);
}
for (const s of settings.spacing.spacingSizes) out(`\t--wp--preset--spacing--${s.slug}: ${s.size};`);
for (const s of settings.shadow?.presets ?? []) out(`\t--wp--preset--shadow--${s.slug}: ${s.shadow};`);
const custom = (obj, prefix) => {
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === 'object') custom(v, `${prefix}--${k}`);
    else out(`\t--wp--custom${prefix}--${k}: ${v};`);
  }
};
custom(settings.custom ?? {}, '');
out(`\t--wp--style--global--content-size: ${settings.layout.contentSize};`);
out(`\t--wp--style--global--wide-size: ${settings.layout.wideSize};`);
out(`\t--wp--style--root--padding-left: ${ref(styles.spacing.padding.left)};`);
out(`\t--wp--style--root--padding-right: ${ref(styles.spacing.padding.right)};`);
out(`\t--wp--style--block-gap: ${ref(styles.spacing.blockGap)};`);
out('}');
out();
out('/* Preset classes WordPress adds to block markup. */');
for (const c of settings.color.palette) {
  out(`.has-${c.slug}-color { color: var(--wp--preset--color--${c.slug}) !important; }`);
  out(`.has-${c.slug}-background-color { background-color: var(--wp--preset--color--${c.slug}) !important; }`);
  out(`.has-${c.slug}-border-color { border-color: var(--wp--preset--color--${c.slug}) !important; }`);
}
for (const g of settings.color.gradients ?? []) {
  out(`.has-${g.slug}-gradient-background { background: var(--wp--preset--gradient--${g.slug}) !important; }`);
}
for (const f of settings.typography.fontSizes) {
  out(`.has-${f.slug}-font-size { font-size: var(--wp--preset--font-size--${f.slug}) !important; }`);
}
for (const f of settings.typography.fontFamilies) {
  out(`.has-${f.slug}-font-family { font-family: var(--wp--preset--font-family--${f.slug}) !important; }`);
}
out();

/* ------------------------------------------------ element & block styles -- */

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** theme.json style object -> CSS declarations (the subset this theme uses). */
function declarations(style) {
  const d = [];
  const c = style.color ?? {};
  if (c.text) d.push(`color: ${ref(c.text)}`);
  if (c.gradient) d.push(`background: ${ref(c.gradient)}`);
  if (c.background) d.push(`background-color: ${ref(c.background)}`);
  for (const [k, v] of Object.entries(style.typography ?? {})) d.push(`${kebab(k)}: ${ref(v)}`);
  const sp = style.spacing ?? {};
  for (const side of ['top', 'right', 'bottom', 'left']) {
    if (sp.padding?.[side] !== undefined) d.push(`padding-${side}: ${ref(sp.padding[side])}`);
  }
  const b = style.border ?? {};
  for (const k of ['color', 'style', 'width', 'radius']) if (typeof b[k] === 'string') d.push(`border-${k}: ${ref(b[k])}`);
  for (const side of ['top', 'right', 'bottom', 'left']) {
    for (const [k, v] of Object.entries(b[side] ?? {})) d.push(`border-${side}-${k}: ${ref(v)}`);
  }
  return d;
}

const rule = (selector, style) => {
  const d = declarations(style);
  if (d.length) out(`${selector} { ${d.join('; ')}; }`);
};

const ELEMENTS = {
  link: 'a:not(.wp-element-button)',
  heading: 'h1, h2, h3, h4, h5, h6',
  h1: 'h1', h2: 'h2', h3: 'h3', h4: 'h4', h5: 'h5', h6: 'h6',
  button: '.wp-element-button, .wp-block-button__link',
  caption: '.wp-element-caption, figcaption',
  cite: 'cite',
};

/** Element styles under a scope ("" for the root, ".is-style-x" for a section). */
function elementRules(elements, scope) {
  for (const [name, style] of Object.entries(elements ?? {})) {
    const sel = ELEMENTS[name];
    if (!sel) continue;
    const scoped = (s) => (scope ? `${scope} :where(${s})` : `:root :where(${s})`);
    rule(scoped(sel), style);
    for (const state of [':hover', ':focus']) {
      if (style[state]) rule(sel.split(', ').map((x) => scoped(`${x}${state}`)).join(', '), style[state]);
    }
  }
}

out('/* Element styles (theme.json styles.elements). */');
rule('body', { color: styles.color, typography: styles.typography });
elementRules(styles.elements, '');
out();
out('/* Block styles (theme.json styles.blocks). */');
for (const [block, style] of Object.entries(styles.blocks ?? {})) {
  const cls = `.wp-block-${block.replace(/^core\//, '').replace('/', '-')}`;
  rule(`:root :where(${cls})`, style);
  elementRules(style.elements, `:root :where(${cls})`);
}
out();
out('/* Section styles (styles/sections/*.json). */');
const sectionsDir = resolve(themeDir, 'styles/sections');
for (const file of readdirSync(sectionsDir).filter((f) => f.endsWith('.json')).sort()) {
  const v = JSON.parse(readFileSync(resolve(sectionsDir, file), 'utf8'));
  const scope = `.is-style-${v.slug}`;
  rule(`:root :where(${scope})`, v.styles);
  elementRules(v.styles.elements, `:root ${scope}`);
  for (const [block, style] of Object.entries(v.styles.blocks ?? {})) {
    rule(`:root ${scope} :where(.wp-block-${block.replace(/^core\//, '')})`, style);
  }
}
out();

writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath} (${lines.length} lines)`);

/* ------------------------------------------------------- theme CSS copies -- */

const copies = [
  ['assets/css/theme.css', 'theme.css'],
  ['blocks/blocks.css', 'blocks.css'],
];
mkdirSync(resolve(here, '../src/styles/theme'), { recursive: true });
for (const [from, to] of copies) {
  const css = readFileSync(resolve(themeDir, from), 'utf8');
  const dest = resolve(here, '../src/styles/theme', to);
  writeFileSync(dest, `/* Copied from the WordPress theme (${from}) by scripts/sync-tokens.mjs. Edit it there, then run npm run sync:tokens. */\n\n${css}`);
  console.log(`Wrote ${dest}`);
}
